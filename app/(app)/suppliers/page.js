'use client';

import { useMemo, useState } from 'react';
import toast from 'react-hot-toast';
import {
  Building2,
  Mail,
  MapPin,
  Pencil,
  Phone,
  Plus,
  Search,
  Trash2,
  Truck,
  UserRound,
} from 'lucide-react';
import { useApp } from '@/context/AppProvider';
import {
  Badge,
  Button,
  ConfirmDialog,
  DemoNote,
  EmptyState,
  Modal,
  PageHeader,
  SearchInput,
  SectionCard,
  StatusBadge,
  cn,
} from '@/components/ui';
import SupplierFormModal from '@/components/suppliers/SupplierFormModal';
import { getStockStatus } from '@/lib/inventoryRules';

export default function SuppliersPage() {
  const {
    suppliers,
    products,
    canDo,
    addSupplier,
    updateSupplier,
    deleteSupplier,
  } = useApp();

  const canManage = canDo('suppliers.manage');
  const [search, setSearch] = useState('');
  const [formOpen, setFormOpen] = useState(false);
  const [editingSupplier, setEditingSupplier] = useState(null);
  const [detailSupplier, setDetailSupplier] = useState(null);
  const [deleteTarget, setDeleteTarget] = useState(null);

  const productsBySupplier = useMemo(() => {
    const map = new Map();
    for (const product of products) {
      if (!product.supplierId) continue;
      if (!map.has(product.supplierId)) map.set(product.supplierId, []);
      map.get(product.supplierId).push(product);
    }
    return map;
  }, [products]);

  const filteredSuppliers = useMemo(() => {
    const query = search.trim().toLowerCase();
    if (!query) return suppliers;
    return suppliers.filter((supplier) =>
      [supplier.name, supplier.contactPerson, supplier.email, supplier.phone, supplier.address]
        .filter(Boolean)
        .some((field) => String(field).toLowerCase().includes(query))
    );
  }, [suppliers, search]);

  const assignedCount = products.filter((product) => product.supplierId).length;
  const unassignedCount = products.length - assignedCount;

  const handleSubmit = (values) => {
    const result = editingSupplier
      ? updateSupplier(editingSupplier.id, values)
      : addSupplier(values);
    if (result.ok) {
      toast.success(editingSupplier ? 'Supplier details updated.' : 'Supplier added to the directory.');
      if (detailSupplier?.id === editingSupplier?.id) {
        setDetailSupplier(result.supplier);
      }
    }
    return result;
  };

  const handleDelete = () => {
    if (!deleteTarget) return;
    const result = deleteSupplier(deleteTarget.id);
    if (result.ok) {
      toast.success(`${deleteTarget.name} was removed from the directory.`);
      if (detailSupplier?.id === deleteTarget.id) setDetailSupplier(null);
    } else if (!result.denied) {
      toast.error(result.error);
    }
    setDeleteTarget(null);
  };

  return (
    <div>
      <PageHeader
        title="Suppliers"
        eyebrow="Supplier directory"
        icon={Truck}
        subtitle="Maintain supplier contacts and assign them to products. Supplier information is demonstration data and is never generated by the chatbot."
        badges={<DemoNote />}
        actions={
          canManage ? (
            <Button
              icon={Plus}
              onClick={() => {
                setEditingSupplier(null);
                setFormOpen(true);
              }}
              data-tour="add-supplier-button"
            >
              Add supplier
            </Button>
          ) : (
            <Badge tone="slate">Read-only role</Badge>
          )
        }
      />

      <div className="mb-4 grid grid-cols-3 gap-3">
        {[
          { label: 'Suppliers', value: suppliers.length },
          { label: 'Products assigned', value: assignedCount },
          { label: 'Unassigned products', value: unassignedCount },
        ].map((item) => (
          <div key={item.label} className="card px-4 py-3">
            <p className="text-[10.5px] font-bold uppercase tracking-wide text-slate-500">{item.label}</p>
            <p className="mt-1 text-xl font-extrabold text-slate-900">{item.value}</p>
          </div>
        ))}
      </div>

      <div data-tour="supplier-list">
        <SectionCard
          title="Supplier records"
          subtitle={`${filteredSuppliers.length} of ${suppliers.length} supplier(s)`}
          icon={Building2}
          action={
            <SearchInput
              value={search}
              onChange={setSearch}
              placeholder="Search suppliers…"
              className="w-full sm:w-64"
            />
          }
        >
          {filteredSuppliers.length === 0 ? (
            <EmptyState
              icon={Search}
              title={search ? 'No suppliers match your search' : 'No suppliers yet'}
              message={
                search
                  ? 'Try a different name, contact person, or email.'
                  : 'Add a supplier to start assigning it to products.'
              }
              action={
                !search && canManage ? (
                  <Button
                    size="sm"
                    icon={Plus}
                    onClick={() => {
                      setEditingSupplier(null);
                      setFormOpen(true);
                    }}
                  >
                    Add supplier
                  </Button>
                ) : null
              }
            />
          ) : (
            <div className="grid gap-3 sm:grid-cols-2 xl:grid-cols-3">
              {filteredSuppliers.map((supplier) => {
                const assigned = productsBySupplier.get(supplier.id) || [];
                return (
                  <div
                    key={supplier.id}
                    className="flex flex-col rounded-2xl border border-slate-200 bg-white p-4 transition hover:border-brand-200 hover:shadow-sm"
                  >
                    <div className="flex items-start justify-between gap-2">
                      <div className="flex items-start gap-2.5">
                        <span className="grid h-10 w-10 shrink-0 place-items-center rounded-xl bg-brand-50 text-brand-600">
                          <Building2 size={18} />
                        </span>
                        <div className="min-w-0">
                          <p className="text-[13px] font-bold leading-snug text-slate-900">
                            {supplier.name}
                          </p>
                          <p className="mt-0.5 flex items-center gap-1 text-[11px] text-slate-500">
                            <UserRound size={11} /> {supplier.contactPerson}
                          </p>
                        </div>
                      </div>
                      <Badge tone={assigned.length ? 'brand' : 'slate'}>
                        {assigned.length} product{assigned.length === 1 ? '' : 's'}
                      </Badge>
                    </div>

                    <div className="mt-3 space-y-1.5 text-[11px] text-slate-600">
                      <p className="flex items-center gap-1.5">
                        <Phone size={11} className="text-slate-400" /> {supplier.phone}
                      </p>
                      <p className="flex items-center gap-1.5 truncate">
                        <Mail size={11} className="shrink-0 text-slate-400" />
                        <span className="truncate">{supplier.email || 'No email on file'}</span>
                      </p>
                      <p className="flex items-start gap-1.5">
                        <MapPin size={11} className="mt-0.5 shrink-0 text-slate-400" />
                        <span className="line-clamp-2">{supplier.address || 'No address on file'}</span>
                      </p>
                    </div>

                    <div className="mt-3 flex flex-wrap gap-1.5">
                      {assigned.slice(0, 3).map((product) => (
                        <span
                          key={product.id}
                          className={cn(
                            'rounded-full px-2 py-0.5 text-[9.5px] font-semibold ring-1 ring-inset',
                            getStockStatus(product).badge
                          )}
                        >
                          {product.sku}
                        </span>
                      ))}
                      {assigned.length > 3 ? (
                        <span className="rounded-full bg-slate-100 px-2 py-0.5 text-[9.5px] font-semibold text-slate-500">
                          +{assigned.length - 3} more
                        </span>
                      ) : null}
                    </div>

                    <div className="mt-auto flex items-center justify-between gap-2 border-t border-slate-100 pt-3">
                      <button
                        type="button"
                        onClick={() => setDetailSupplier(supplier)}
                        className="text-[11px] font-bold text-brand-700 hover:underline"
                      >
                        View details
                      </button>
                      {canManage ? (
                        <div className="flex items-center gap-0.5">
                          <button
                            type="button"
                            onClick={() => {
                              setEditingSupplier(supplier);
                              setFormOpen(true);
                            }}
                            className="grid h-7 w-7 place-items-center rounded-md text-slate-400 hover:bg-brand-50 hover:text-brand-700"
                            title="Edit supplier"
                            aria-label={`Edit ${supplier.name}`}
                          >
                            <Pencil size={14} />
                          </button>
                          <button
                            type="button"
                            onClick={() => setDeleteTarget(supplier)}
                            className="grid h-7 w-7 place-items-center rounded-md text-slate-400 hover:bg-rose-50 hover:text-rose-600"
                            title="Delete supplier"
                            aria-label={`Delete ${supplier.name}`}
                          >
                            <Trash2 size={14} />
                          </button>
                        </div>
                      ) : null}
                    </div>
                  </div>
                );
              })}
            </div>
          )}
        </SectionCard>
      </div>

      <SupplierFormModal
        open={formOpen}
        onClose={() => {
          setFormOpen(false);
          setEditingSupplier(null);
        }}
        supplier={editingSupplier}
        onSubmit={handleSubmit}
      />

      <Modal
        open={Boolean(detailSupplier)}
        onClose={() => setDetailSupplier(null)}
        size="lg"
        icon={Building2}
        title={detailSupplier?.name || 'Supplier'}
        description="Supplier record and assigned products"
        footer={
          <>
            <Button variant="secondary" onClick={() => setDetailSupplier(null)}>
              Close
            </Button>
            {canManage ? (
              <Button
                icon={Pencil}
                onClick={() => {
                  setEditingSupplier(detailSupplier);
                  setDetailSupplier(null);
                  setFormOpen(true);
                }}
              >
                Edit supplier
              </Button>
            ) : null}
          </>
        }
      >
        {detailSupplier ? (
          <div className="space-y-4">
            <div className="grid gap-3 sm:grid-cols-2">
              {[
                ['Contact person', detailSupplier.contactPerson],
                ['Phone', detailSupplier.phone],
                ['Email', detailSupplier.email || '—'],
                ['Address', detailSupplier.address || '—'],
              ].map(([label, value]) => (
                <div key={label} className="rounded-xl border border-slate-200 p-3">
                  <p className="text-[10px] font-bold uppercase tracking-wide text-slate-400">{label}</p>
                  <p className="mt-0.5 text-[12px] font-medium text-slate-800">{value}</p>
                </div>
              ))}
            </div>
            {detailSupplier.notes ? (
              <p className="rounded-xl bg-slate-50 p-3 text-[11.5px] leading-relaxed text-slate-600">
                {detailSupplier.notes}
              </p>
            ) : null}
            <div>
              <p className="mb-2 text-[11px] font-bold uppercase tracking-wide text-slate-500">
                Assigned products
              </p>
              {(productsBySupplier.get(detailSupplier.id) || []).length === 0 ? (
                <p className="rounded-xl border border-dashed border-slate-200 p-4 text-center text-xs text-slate-500">
                  No products are assigned to this supplier yet.
                </p>
              ) : (
                <div className="divide-y divide-slate-100 rounded-xl border border-slate-200">
                  {(productsBySupplier.get(detailSupplier.id) || []).map((product) => (
                    <div key={product.id} className="flex items-center justify-between gap-3 px-3 py-2.5">
                      <div>
                        <p className="text-[12px] font-semibold text-slate-800">{product.name}</p>
                        <p className="text-[10px] text-slate-400">{product.sku}</p>
                      </div>
                      <div className="flex items-center gap-3">
                        <span className="text-[11px] text-slate-500">{product.stock} on hand</span>
                        <StatusBadge product={product} />
                      </div>
                    </div>
                  ))}
                </div>
              )}
            </div>
          </div>
        ) : null}
      </Modal>

      <ConfirmDialog
        open={Boolean(deleteTarget)}
        onClose={() => setDeleteTarget(null)}
        onConfirm={handleDelete}
        title="Delete supplier?"
        message={
          deleteTarget
            ? `${deleteTarget.name} will be removed from the demonstration directory. Suppliers assigned to products cannot be deleted until those products are reassigned.`
            : ''
        }
        confirmLabel="Delete supplier"
        tone="danger"
        icon={Trash2}
      />
    </div>
  );
}
